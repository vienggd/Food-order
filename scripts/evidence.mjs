// Runs every test suite on a clean tree and writes evidence tied to the tested commit (Issue #11).
// Usage: npm run evidence   (needs Docker DB up, server/.env, Playwright chromium installed)
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";

const sh = (cmd, opts = {}) => execSync(cmd, { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], ...opts });
const tmp = "docs/evidence/.raw";
mkdirSync(tmp, { recursive: true });

const dirty = sh("git status --porcelain").split("\n").filter((l) => l.trim() && !l.slice(3).startsWith("docs/evidence/"));
if (dirty.length) {
  console.error("Working tree has changes outside docs/evidence. Commit them first so the evidence matches a commit.");
  process.exit(1);
}
const commit = sh("git rev-parse HEAD").trim();
const branch = sh("git rev-parse --abbrev-ref HEAD").trim();
const when = new Date().toISOString();

// 1. Run the suites with JSON output (a failing suite must not stop the report).
const run = (cmd, env = {}) => {
  try {
    sh(cmd, { env: { ...process.env, ...env } });
    return 0;
  } catch (e) {
    return e.status ?? 1;
  }
};
const exit = {
  server: run(`cd server && npx vitest run --reporter=json --outputFile=../${tmp}/server.json`),
  client: run(`cd client && npx vitest run --reporter=json --outputFile=../${tmp}/client.json`),
  e2e: run(`npx playwright test --reporter=json`, { PLAYWRIGHT_JSON_OUTPUT_NAME: `${tmp}/e2e.json` }),
  build: run("npm run build"),
};

// 2. Flatten results to { suite, file, name, status }.
const results = [];
for (const suite of ["server", "client"]) {
  const j = JSON.parse(readFileSync(`${tmp}/${suite}.json`, "utf8"));
  for (const f of j.testResults) {
    const file = f.name.replace(/\\/g, "/").replace(/^.*?\/(server|client)\//, "$1/");
    for (const a of f.assertionResults) results.push({ suite, file, name: a.fullName ?? a.title, status: a.status === "passed" ? "passed" : a.status });
  }
}
const e2e = JSON.parse(readFileSync(`${tmp}/e2e.json`, "utf8"));
const walk = (s, file) => {
  for (const spec of s.specs ?? [])
    for (const t of spec.tests)
      results.push({ suite: `e2e ${t.projectName}`, file: `e2e/${spec.file ?? file}`, name: spec.title, status: t.status === "expected" ? "passed" : t.status === "skipped" ? "skipped" : "failed" });
  for (const c of s.suites ?? []) walk(c, s.file ?? file);
};
for (const s of e2e.suites) walk(s, s.file);

// 3. Counts per suite.
const suites = [...new Set(results.map((r) => r.suite))];
const count = (s, st) => results.filter((r) => r.suite === s && r.status === st).length;
const countsTable = suites
  .map((s) => `| ${s} | ${results.filter((r) => r.suite === s).length} | ${count(s, "passed")} | ${count(s, "failed")} | ${count(s, "skipped")} |`)
  .join("\n");

// 4. AC -> tests from the contracts' test specification tables.
const contractDir = "docs/sprints/sprint-1";
const acTests = new Map(); // AC -> [{ id, level }]
const acText = new Map();
for (const f of readdirSync(contractDir).filter((n) => /^F-0\d.*\.md$/.test(n))) {
  for (const line of readFileSync(`${contractDir}/${f}`, "utf8").split(/\r?\n/)) {
    const cells = line.split("|").map((c) => c.trim());
    if (/^TEST-F0\d-\d+$/.test(cells[1] ?? "")) {
      for (const ac of cells[2].match(/AC-F0\d-\d+/g) ?? []) {
        if (!acTests.has(ac)) acTests.set(ac, []);
        acTests.get(ac).push({ id: cells[1], level: cells[3] });
      }
    } else if (/^AC-F0\d-\d+$/.test(cells[1] ?? "")) acText.set(cells[1], cells[2].replace(/\*\*/g, "").slice(0, 90));
  }
}
const acs = [...new Set([...acText.keys(), ...acTests.keys()])].sort();
const acRows = acs.map((ac) => {
  const tests = acTests.get(ac) ?? [];
  const found = tests.flatMap((t) => results.filter((r) => r.name.includes(t.id)).map((r) => ({ ...r, id: t.id, level: t.level })));
  const result = !tests.length ? "NO TEST PLANNED" : !found.length ? "NOT FOUND" : found.every((r) => r.status === "passed") ? "Pass" : "FAIL";
  const where = [...new Set(found.map((r) => `${r.file} › ${r.name.replace(/^.*?(TEST-)/, "$1")}${r.suite.startsWith("e2e") ? " (phone + desktop)" : ""}`))].join("<br>");
  return `| ${ac} | ${acText.get(ac) ?? ""} | ${[...new Set(tests.map((t) => `${t.id} (${t.level})`))].join(", ")} | ${where || "—"} | ${result} |`;
});
const bad = acRows.filter((r) => !r.endsWith("| Pass |")).length;

const header = `Tested commit: \`${commit}\` (branch \`${branch}\`), run at ${when}. Generated by \`npm run evidence\` (scripts/evidence.mjs) — do not edit by hand.`;

writeFileSync(
  "docs/evidence/test-run.md",
  `# Sprint 1 test run\n\n${header}\n\n## Commands\n\n| Suite | Command | Exit code |\n|---|---|---|\n| server (unit + API, real Postgres \`cafe_test\`) | \`npm test -w server\` | ${exit.server} |\n| client (unit) | \`npm test -w client\` | ${exit.client} |\n| E2E (Playwright, \`cafe_e2e\`, phone 375 px + desktop 1280 px) | \`npm run test:e2e\` | ${exit.e2e} |\n| build (server tsc + client tsc/vite) | \`npm run build\` | ${exit.build} |\n\n## Counts\n\n| Suite | Tests | Passed | Failed | Skipped |\n|---|---|---|---|---|\n${countsTable}\n\n## Every test\n\n| Suite | File | Test | Result |\n|---|---|---|---|\n${results.map((r) => `| ${r.suite} | ${r.file} | ${r.name} | ${r.status} |`).join("\n")}\n`,
);
writeFileSync(
  "docs/evidence/ac-results.md",
  `# Sprint 1 acceptance criteria → tests → results\n\n${header}\n\nAll tests below are automated. Planned tests come from each contract's test specification (\`docs/sprints/sprint-1/F-0x-*.md\`); a result is **Pass** only if every matching test passed in this run.\n\n${acs.length} AC; ${acs.length - bad} Pass; ${bad} not Pass.\n\n| AC | Criterion (short) | Planned tests | Test file › name | Result |\n|---|---|---|---|---|\n${acRows.join("\n")}\n`,
);
// 5. Refresh the generated blocks in Part F of the PDF (docs/evidence/part-f.md).
const partF = "docs/evidence/part-f.md";
let board = "";
try {
  const items = JSON.parse(sh("gh project item-list 4 --owner vienggg --format json --limit 100")).items;
  board = `Board https://github.com/users/vienggg/projects/4 read at ${when}:\n\n| Issue | Title | Column |\n|---|---|---|\n${items
    .sort((a, b) => a.content.number - b.content.number)
    .map((i) => `| #${i.content.number} | ${i.title} | ${i.status} |`)
    .join("\n")}`;
} catch {
  board = "_Board could not be read (gh not logged in)._";
}
const blocks = {
  COMMIT: `${header}\n\n**Release reference:** branch \`sprint-1\`; the release to \`main\` and tag \`v0.1.0-sprint1\` are made by the students — if a release is made, \`npm run evidence\` is run again on it and this line names it.`,
  COUNTS: `| Suite | Command | Exit code |\n|---|---|---|\n| server unit + API (real Postgres \`cafe_test\`) | \`npm test -w server\` | ${exit.server} |\n| client unit | \`npm test -w client\` | ${exit.client} |\n| E2E (Playwright, \`cafe_e2e\`) | \`npm run test:e2e\` | ${exit.e2e} |\n| build | \`npm run build\` | ${exit.build} |\n\n| Suite | Tests | Passed | Failed | Skipped |\n|---|---|---|---|---|\n${countsTable}`,
  "AC-TABLE": `${acs.length} AC; ${acs.length - bad} Pass; ${bad} not Pass.\n\n| AC | Criterion (short) | Planned tests | Test file › name | Result |\n|---|---|---|---|---|\n${acRows.join("\n")}`,
  BOARD: board,
};
try {
  let text = readFileSync(partF, "utf8");
  for (const [name, body] of Object.entries(blocks)) {
    text = text.replace(new RegExp(`<!-- ${name} -->[\\s\\S]*?<!-- /${name} -->`), `<!-- ${name} -->\n${body}\n<!-- /${name} -->`);
  }
  writeFileSync(partF, text);
} catch {
  // part-f.md not present on this branch: nothing to refresh
}

console.log(`commit ${commit}`);
console.log(suites.map((s) => `${s}: ${count(s, "passed")} passed, ${count(s, "failed")} failed, ${count(s, "skipped")} skipped`).join("\n"));
console.log(`build exit ${exit.build}; AC: ${acs.length} total, ${bad} not Pass`);
process.exitCode = Object.values(exit).some((c) => c) || bad ? 1 : 0;
